class Solution:
    def isPalindrome(self, s: str) -> bool:
        # O(n) по времени — указатели движутся навстречу друг другу, выполняется не более n/2 сравнений.
        # Запускаем два указателя с начала и с конца. Соответствующие им элементы всегда должны быть равны если строка - палиндром
        i = 0
        j = len(s) - 1
        while i < j:
            if s[i] != s[j]:
                return False
            i += 1
            j -= 1
        return True

